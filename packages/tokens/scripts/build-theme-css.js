// Generates dist/theme.css from the compiled tokens so CSS and TS never drift apart.
import { writeFileSync } from 'node:fs';
import { colors } from '../dist/index.js';

const lines = Object.entries(colors).flatMap(([group, values]) =>
    Object.entries(values).map(([name, value]) => `  --color-${group}-${name}: ${value};`),
);

const css = `/* Generated by @vet-plan/tokens — do not edit. Source: src/index.ts */
@theme {
${lines.join('\n')}
}
`;

writeFileSync(new URL('../dist/theme.css', import.meta.url), css);
